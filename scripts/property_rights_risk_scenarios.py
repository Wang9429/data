def kri(name, definition, calc, where, rule):
    return f"指标名称：{name}→指标定义：{definition}→指标计算：{calc}→其中：{where}→监控规则：{rule}"

def stage(pre, mid="", post=""):
    parts = ["以事前控制为主，事中监测为辅。"]
    detail = []
    if pre:
        detail.append(f"事前通过{pre}")
    if mid:
        detail.append(f"事中通过{mid}")
    if post:
        detail.append(f"事后通过{post}")
    return parts[0] + "\n" + "；".join(detail) + "。"

