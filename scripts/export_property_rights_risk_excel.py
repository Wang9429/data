def kri(name, definition, calc, where, rule):
    parts = [
        f"指标名称：{name}",
        f"指标定义：{definition}",
        f"指标计算：{calc}",
    ]
    if where:
        parts.append(f"其中，{where}")
    parts.append(f"监控规则：{rule}")
    return "\n".join(parts)


